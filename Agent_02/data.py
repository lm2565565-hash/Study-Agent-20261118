def get_competitor_info(product_id: str):
    '''
    根据商品编号获取竞品信息
    :param product_id:
    :return:
    '''
    if product_id in jingping:
        return jingping[product_id]
    # 没有提前配置好的竞品数据  就去模拟生成
    product = products[product_id]
    index = int(product_id[1:])
    competitor_count = (index * 7) % 30 + 10  # 13*7   91%30=1  +10= 11
    average_price = round(product['price'] * (0.94 + (index % 5) * 0.025), 2)
    mouthly_sales = 80 + (index * 35) % 350
    competition_score = min(95, competitor_count * 2 + (index % 7) * 2)
    return {
        'competitor_count': competitor_count,
        'average_price': average_price,
        'monthly_sales': mouthly_sales,
        'competition_score': competition_score,
    }
